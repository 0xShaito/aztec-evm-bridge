export const getAztecWallet = async (): Promise<AccountWithSecretKey> => {
  if (account) {
    return account
  }

  const secretKey = Fr.fromHexString(process.env.AZTEC_SECRET_KEY as string)
  const salt = Fr.fromHexString(process.env.AZTEC_SALT as string)

  // Create account using TestWallet (don't deploy - account already exists on devnet)
  const accountContract = await wallet.createSchnorrAccount(secretKey, salt)
  account = await accountContract.getAccount()

  return account
}

export const initPxe = async () => {
  const node = await getAztecNode()
  const fullConfig = {
    ...getPXEConfig(),
    l1Contracts: await node.getL1ContractAddresses(),
    proverEnabled: process.env.AZTEC_PROVER_ENABLED === "true",
  }
  const store = await createStore("filler-pxe", {
    dataDirectory: "store",
    dataStoreMapSizeKb: 1e6,
  })

  // Create TestWallet instead of raw PXE
  wallet = await TestWallet.create(node, fullConfig, {
    store,
    useLogSuffix: true,
  })

  // Keep reference to PXE for backward compatibility
  pxe = wallet as any
}

export const registerContracts = async ({
  aztecGatewayAddress,
  aztecTokenAddress,
}: {
  aztecGatewayAddress: string
  aztecTokenAddress?: string
}) => {
  await wallet.registerContract({
    instance: await getSponsoredFPCInstance(),
    artifact: SponsoredFPCContractArtifact,
  })
  await wallet.registerSender(AztecAddress.fromString(aztecGatewayAddress))

  // Try to register the gateway contract if it exists on the node
  try {
    const node = await getAztecNode()
    const gatewayInstance = await node.getContract(AztecAddress.fromString(aztecGatewayAddress))

    if (!gatewayInstance) {
      console.warn(`Gateway contract not found on node at ${aztecGatewayAddress}`)
      console.warn("The gateway contract may not be deployed yet on this node.")
    } else {
      // Check if class IDs match
      const { getContractClassFromArtifact } = await import("@aztec/aztec.js/contracts")
      const artifact = await getAztecGateway7683ContractArtifact()
      const artifactClass = await getContractClassFromArtifact(artifact)
      const instanceClassId = gatewayInstance.currentContractClassId

      if (!instanceClassId.equals(artifactClass.id)) {
        console.warn(
          `⚠️  Gateway contract class ID mismatch! ` +
            `Instance: ${instanceClassId.toString()}, ` +
            `Expected: ${artifactClass.id.toString()}. ` +
            `Attempting to get artifact from node...`,
        )
        // Try to get the artifact from the node
        try {
          const classMetadata = await pxe.getContractClassMetadata(instanceClassId, true)
          if (classMetadata?.artifact) {
            await pxe.registerContract({
              instance: gatewayInstance as ContractInstanceWithAddress,
              artifact: classMetadata.artifact,
            })
            console.log(`✅ Registered gateway contract using artifact from node`)
          } else {
            throw new Error("Contract class metadata not available from node")
          }
        } catch (err2: any) {
          console.warn(`Could not get gateway contract class from node: ${err2.message}`)
          // Try registering without artifact - requires artifact to be pre-registered
          try {
            await pxe.registerContract({
              instance: gatewayInstance as ContractInstanceWithAddress,
            })
            console.log(`✅ Registered gateway contract instance (artifact may need to be registered separately)`)
          } catch (err3: any) {
            throw new Error(`Failed to register gateway contract: ${err3.message}`)
          }
        }
      } else {
        // Class IDs match - register normally
        const artifact = await getAztecGateway7683ContractArtifact()
        await registerContractWithoutInstance(AztecAddress.fromString(aztecGatewayAddress), {
          artifact,
        })
        console.log(`✅ Registered gateway contract at ${aztecGatewayAddress}`)
      }
    }
  } catch (err) {
    const errorMessage = err instanceof Error ? err.message : String(err)
    console.warn(`Warning: Could not register gateway contract at ${aztecGatewayAddress}: ${errorMessage}`)
    console.warn("The gateway contract may not be deployed yet on this node.")
    console.warn("It will be attempted to register dynamically when needed.")
    // Don't throw - allow the filler to continue and try dynamic registration later
  }

  // Register the deployed token contract if address is provided
  if (aztecTokenAddress) {
    try {
      const { TokenContractArtifact } = await import("@defi-wonderland/aztec-standards/current/artifacts/Token.js")
      const node = await getAztecNode()
      const contractInstance = await node.getContract(AztecAddress.fromString(aztecTokenAddress))

      if (contractInstance) {
        const { getContractClassFromArtifact } = await import("@aztec/aztec.js/contracts")
        const artifactClass = await getContractClassFromArtifact(TokenContractArtifact)
        const instanceClassId = contractInstance.currentContractClassId

        if (!instanceClassId.equals(artifactClass.id)) {
          console.warn(
            `⚠️  Token contract class ID mismatch! ` +
              `Instance: ${instanceClassId.toString()}, ` +
              `Expected: ${artifactClass.id.toString()}. ` +
              `This suggests the token was deployed with a different version of the token contract.`,
          )
          console.warn("Attempting to register with the actual deployed contract class...")

          // Try to get the contract class metadata from the node (with artifact)
          try {
            const classMetadata = await pxe.getContractClassMetadata(instanceClassId, true)
            if (classMetadata?.artifact) {
              // Use the artifact from the node that matches the deployed class ID
              await pxe.registerContract({
                instance: contractInstance as ContractInstanceWithAddress,
                artifact: classMetadata.artifact,
              })
              console.log(
                `✅ Registered token contract using artifact from node (class ID: ${instanceClassId.toString()})`,
              )
            } else {
              throw new Error("Contract class metadata not available from node")
            }
          } catch (err2: any) {
            console.warn(`Could not get contract class from node: ${err2.message}`)
            // Fall back to trying without artifact validation
            await pxe.registerContract({
              instance: contractInstance as ContractInstanceWithAddress,
            })
            console.log(`✅ Registered token contract instance (artifact may need to be registered separately)`)
          }
        } else {
          // Class IDs match - register normally
          await registerContractWithoutInstance(AztecAddress.fromString(aztecTokenAddress), {
            artifact: TokenContractArtifact,
          })
          console.log(`✅ Registered token contract at ${aztecTokenAddress}`)
        }
      }
    } catch (err) {
      console.warn(`Warning: Could not register token contract: ${err instanceof Error ? err.message : err}`)
      console.warn("The token contract may need to be registered dynamically when orders are processed.")
    }
  }
}

