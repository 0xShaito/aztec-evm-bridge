// Import artifact JSON directly and load it lazily to avoid module load-time errors
// We'll import the artifact when needed instead of at module load time
let AztecGateway7683ContractArtifact: any = null

export async function getAztecGateway7683ContractArtifact() {
  if (!AztecGateway7683ContractArtifact) {
    // Import from the TypeScript artifact file (same as deployment script uses)
    // The deployment script successfully uses this, so it should work here too
    // The artifact is already generated by aztec codegen with proper transpiled bytecode
    const { AztecGateway7683Contract } = await import(
      "../../../aztec/aztec_gateway_7683/src/artifacts/AztecGateway7683.ts"
    )
    AztecGateway7683ContractArtifact = AztecGateway7683Contract.artifact
  }
  return AztecGateway7683ContractArtifact
}

